"""Run the whole CNC DTW labelling pipeline end to end.

The stages were previously driven by hand, one command at a time, with the
output directory suffix (``_top10`` / ``_all_best`` / ``_tool6``) retyped at
every step.  That made it easy to mix outputs from different runs -- several of
the original ``processed/`` folders were generated by different versions of the
code -- and left no record of what produced what.

Every stage writes a ``run_manifest.json`` recording its arguments, package
versions and timestamp, so an output folder can always be traced back.

Usage
-----
    python scripts/run_pipeline.py --data-dir data --suffix all_best --all-windows
    python scripts/run_pipeline.py --suffix top10 --top-n 10 --skip-preprocess
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent


def run(script: str, arguments: list[str]) -> None:
    command = [sys.executable, str(SCRIPTS / script), *arguments]
    print(f"\n{'=' * 78}\n>>> {script} {' '.join(arguments)}\n{'=' * 78}", flush=True)
    started = time.time()
    result = subprocess.run(command)
    if result.returncode != 0:
        raise SystemExit(f"{script} failed with exit code {result.returncode}")
    print(f"--- {script} finished in {time.time() - started:.1f}s", flush=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the full CNC DTW labelling pipeline.")
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--processed-dir", type=Path, default=Path("processed"))
    parser.add_argument("--suffix", default="all_best",
                        help="Suffix for the per-stage output folders.")
    parser.add_argument("--all-windows", action="store_true",
                        help="Use every best window rather than the top N.")
    parser.add_argument("--top-n", type=int, default=10)
    parser.add_argument("--machine-id", type=int)
    parser.add_argument("--tool")
    parser.add_argument("--primary-reference", default="loo_median")
    parser.add_argument("--trace-mode", default="contiguous")
    parser.add_argument("--permutations", type=int, default=2000)
    parser.add_argument("--skip-preprocess", action="store_true")
    parser.add_argument("--skip-plots", action="store_true")
    parser.add_argument("--legacy-label-names", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    processed = args.processed_dir
    suffix = args.suffix

    comparable = processed / f"comparable_timeseries_{suffix}"
    features = processed / f"dtw_features_{suffix}"
    review = processed / f"dtw_review_{suffix}"
    patterns = processed / f"dtw_patterns_{suffix}"
    candidates = processed / f"dtw_event_candidates_{suffix}"
    evidence = processed / f"robust_event_evidence_{suffix}"
    scored = processed / f"dtw_event_candidates_v2_{suffix}"
    labels = processed / f"labeled_output_{suffix}"

    if not args.skip_preprocess:
        run("preprocess_cnc.py",
            ["--data-dir", str(args.data_dir), "--output-dir", str(processed)])

    run("find_comparable_windows.py", [
        "--input", str(processed / "cnc_run_tool_features.csv"),
        "--output", str(processed / "cnc_dtw_candidate_windows.csv"),
        "--best-output", str(processed / "cnc_dtw_best_windows.csv"),
    ])

    extract = [
        "--windows", str(processed / "cnc_dtw_best_windows.csv"),
        "--samples", str(processed / "cnc_time_series_features.csv.gz"),
        "--run-tools", str(processed / "cnc_run_tool_features.csv"),
        "--output-dir", str(comparable),
        "--trace-mode", args.trace_mode,
    ]
    extract += ["--all-windows"] if args.all_windows else ["--top-n", str(args.top_n)]
    if args.machine_id is not None:
        extract += ["--machine-id", str(args.machine_id)]
    if args.tool is not None:
        extract += ["--tool", str(args.tool)]
    run("create_comparable_timeseries_datasets.py", extract)

    run("build_dtw_features.py", [
        "--input-dir", str(comparable), "--output-dir", str(features),
        "--primary-reference", args.primary_reference,
    ])

    review_args = ["--input-dir", str(features), "--output-dir", str(review)]
    if args.skip_plots:
        review_args.append("--skip-plots")
    run("review_dtw_features.py", review_args)

    run("discover_dtw_patterns.py", [
        "--dtw-dir", str(features), "--output-dir", str(patterns),
        "--permutations", str(args.permutations),
    ])
    run("detect_dtw_event_candidates.py",
        ["--pattern-dir", str(patterns), "--output-dir", str(candidates)])
    run("build_robust_event_evidence.py", [
        "--dtw-dir", str(features), "--candidate-dir", str(candidates),
        "--output-dir", str(evidence),
    ])
    run("score_event_candidates_v2.py", [
        "--candidate-dir", str(candidates), "--evidence-dir", str(evidence),
        "--output-dir", str(scored),
    ])

    label_args = [
        "--v2-candidates", str(scored / "all_event_candidates_v2.csv"),
        "--dtw-features", str(features / "cnc_dtw_features.csv"),
        "--trends", str(evidence / "robust_trend_tests.csv"),
        "--multi-ref", str(evidence / "multi_reference_consensus.csv"),
        "--common-mode", str(evidence / "common_mode_shift_checks.csv"),
        "--comparable-segments", str(comparable / "run_tool_segments.csv"),
        "--samples", str(processed / "cnc_time_series_features.csv.gz"),
        "--output-dir", str(labels),
    ]
    if args.legacy_label_names:
        label_args.append("--legacy-label-names")
    run("apply_algorithmic_labels.py", label_args)

    print(f"\nPipeline complete. Labels in {labels}")


if __name__ == "__main__":
    main()
